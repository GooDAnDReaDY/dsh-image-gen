// @ts-check
// canvas-state.js — In-memory mirror of the workbench infinite canvas (#506, #507).
// Keeps track of active shapes, generated images with provenance, freehand drawings,
// text notes, and in-memory selection screenshots pushed from the browser canvas.

const DIGEST_NODE_LIMIT = 24

/**
 * @typedef {object} CanvasNodeSummary
 * @property {'image'|'draw'|'text'|'note'|'geo'|string} kind
 * @property {string} [name]
 * @property {number} [width]
 * @property {number} [height]
 * @property {string} [attachmentId]
 * @property {string} [provider]
 * @property {string} [model]
 * @property {string} [prompt]
 * @property {string} [text]
 */

/**
 * @typedef {object} CanvasSelectionImage
 * @property {Buffer|Uint8Array} data
 * @property {string} mediaType
 */

/**
 * @typedef {object} CanvasMirrorEntry
 * @property {string} clientInstance
 * @property {boolean} connected
 * @property {number} nodeCount
 * @property {CanvasNodeSummary[]} nodes
 * @property {number} selectionCount
 * @property {string[]} selectionKinds
 * @property {CanvasNodeSummary[]} selectionItems
 * @property {string} selectionSignature
 * @property {CanvasSelectionImage} [selectionImage]
 * @property {number} receivedAt
 * @property {number} seq
 * @property {number} [updatedAt]
 */

function describeNode(node) {
  switch (node.kind) {
    case 'image': {
      const size = typeof node.width === 'number' && typeof node.height === 'number' ? `${node.width}x${node.height}` : undefined
      const name = typeof node.name === 'string' && node.name.length > 0 ? `"${node.name}"` : undefined
      const attachment = typeof node.attachmentId === 'string' ? `attachment ${node.attachmentId}` : undefined
      const generatedBy = typeof node.provider === 'string' && node.provider.length > 0
        ? `generated by ${node.provider}${typeof node.model === 'string' && node.model.length > 0 ? `/${node.model}` : ''}`
        : undefined
      const prompt = typeof node.prompt === 'string' && node.prompt.length > 0 ? `prompt "${node.prompt}"` : undefined
      return ['image', size, name, attachment, generatedBy, prompt].filter(Boolean).join(' ')
    }
    case 'draw':
      return 'draw (freehand stroke)'
    case 'text':
    case 'note': {
      const preview = typeof node.text === 'string' && node.text.length > 0 ? `"${node.text}"` : '(empty)'
      return `${node.kind} ${preview}`
    }
    case 'geo':
      return typeof node.name === 'string' && node.name.length > 0 ? `shape ${node.name}` : 'shape'
    default:
      return node.kind || 'object'
  }
}

export class CanvasMirror {
  constructor() {
    /** @type {Map<string, CanvasMirrorEntry>} */
    this.entries = new Map()
    this.sequences = new Map()
    this.nextSeq = 0
  }

  /**
   * Applies validated state push from browser canvas instance.
   *
   * @param {object} push
   * @param {string} push.clientInstance
   * @param {boolean} [push.connected=true]
   * @param {number} [push.sequence]
   * @param {number} [push.nodeCount=0]
   * @param {CanvasNodeSummary[]} [push.nodes]
   * @param {object} [push.selection]
   * @param {number} [push.selection.count=0]
   * @param {string[]} [push.selection.kinds]
   * @param {CanvasNodeSummary[]} [push.selection.items]
   * @param {number} [push.updatedAt]
   * @param {CanvasSelectionImage} [selectionImage]
   */
  apply(push, selectionImage) {
    if (!push || !push.clientInstance) return

    if (!push.connected) {
      this.entries.delete(push.clientInstance)
      return
    }

    const previous = this.entries.get(push.clientInstance)
    const selectionCount = push.selection?.count ?? 0
    const selectionKinds = Array.isArray(push.selection?.kinds) ? [...push.selection.kinds] : []
    const selectionItems = Array.isArray(push.selection?.items) ? [...push.selection.items] : []
    const selectionSignature = JSON.stringify([selectionCount, selectionKinds, selectionItems])

    const keepImage = previous && previous.selectionSignature === selectionSignature
      ? previous.selectionImage
      : undefined

    this.entries.set(push.clientInstance, {
      clientInstance: push.clientInstance,
      connected: true,
      nodeCount: Number(push.nodeCount) || 0,
      nodes: Array.isArray(push.nodes) ? [...push.nodes] : [],
      selectionCount,
      selectionKinds,
      selectionItems,
      selectionSignature,
      selectionImage: selectionImage || keepImage,
      receivedAt: Date.now(),
      seq: ++this.nextSeq,
      updatedAt: push.updatedAt || Date.now(),
    })
  }

  /**
   * Returns freshest connected entry.
   * @returns {CanvasMirrorEntry|undefined}
   */
  latest() {
    let latestEntry = undefined
    for (const entry of this.entries.values()) {
      if (!latestEntry || entry.seq > latestEntry.seq) {
        latestEntry = entry
      }
    }
    return latestEntry
  }

  /**
   * Returns decoded selection screenshot from freshest connected canvas.
   * @returns {CanvasSelectionImage|undefined}
   */
  latestSelectionImage() {
    const entry = this.latest()
    return entry?.selectionImage
  }

  /**
   * Returns whether any canvas is currently connected.
   * @returns {boolean}
   */
  connected() {
    return this.latest() !== undefined
  }

  /**
   * Generates compact markdown digest of the canvas state for agent and system prompt.
   * @param {number} [now=Date.now()]
   * @returns {string}
   */
  digest(now = Date.now()) {
    const entry = this.latest()
    if (!entry) {
      return 'Image-gen workbench canvas: not connected. No infinite canvas is open right now. If the user refers to drawings or an active canvas, ask them to open the image-gen workbench.'
    }

    const lines = []
    const kindCounts = new Map()
    for (const node of entry.nodes) {
      kindCounts.set(node.kind, (kindCounts.get(node.kind) || 0) + 1)
    }
    const breakdown = [...kindCounts.entries()].map(([kind, count]) => `${count} ${kind}${count === 1 ? '' : 's'}`).join(', ')
    const age = Math.max(0, Math.round((now - entry.receivedAt) / 1000))
    const ageText = age < 5 ? 'just now' : age < 90 ? `${age}s ago` : `${Math.round(age / 60)}min ago`

    lines.push(`Image-gen workbench canvas: ${entry.nodeCount} shape${entry.nodeCount === 1 ? '' : 's'}${breakdown ? ` (${breakdown})` : ''}, updated ${ageText}.`)

    for (const node of entry.nodes.slice(0, DIGEST_NODE_LIMIT)) {
      lines.push(`- ${describeNode(node)}`)
    }
    if (entry.nodes.length > DIGEST_NODE_LIMIT) {
      lines.push(`- ... ${entry.nodes.length - DIGEST_NODE_LIMIT} more shapes omitted`)
    }

    if (entry.selectionCount === 0) {
      lines.push('Selection: none. Ask the user to select shapes on the canvas when they want you to work on something specific.')
    } else {
      const kinds = entry.selectionKinds.length > 0 ? ` (${entry.selectionKinds.join(', ')})` : ''
      lines.push(`Selection: ${entry.selectionCount} shape${entry.selectionCount === 1 ? '' : 's'}${kinds}.`)
      for (const item of entry.selectionItems.slice(0, 10)) {
        lines.push(`  * Selected ${describeNode(item)}`)
      }
      if (entry.selectionImage) {
        lines.push('  * Screenshot available: call view_canvas to materialize and view this selection as an image.')
      }
    }

    return lines.join('\n')
  }

  clear() {
    this.entries.clear()
    this.sequences.clear()
  }
}

let globalCanvasMirror = null

export function getCanvasMirror() {
  if (!globalCanvasMirror) {
    globalCanvasMirror = new CanvasMirror()
  }
  return globalCanvasMirror
}
